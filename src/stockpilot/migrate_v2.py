"""The v1 -> v2 migration (ticket V3, spec #24 amendment "Carry-over from v1").

Every v1 record type is copied into the v2 private store (one parquet file per table under `<out>/<type>/`), and the types a v2 screen
reads also become D1 rows (`<out>/d1/*.json` in the live contract's shape, and one idempotent `seed.sql` for `wrangler d1 execute`).
The proof is a count and a sha256 of every table's rows on both sides; `verify` reads the files again and compares to v1, so a
copy that lost, changed or damaged a row fails in plain words. The manifest holds counts and hashes only, never row content.

Decisions (also on issue #62): "marks" are the "I hold this for years" marks (the v1 table `long_term_marks`); the v2 change marks start empty.
v1 stores naive timestamps; they are read as IST. A watchlist row with `removed_at` stays in the private copy but not in the D1 list.
"""
import hashlib
import json
from datetime import datetime
from pathlib import Path

from stockpilot import jobrun

# record type -> the v1 tables that make it up
RECORD_TYPES = {
    "trades": ["trades"],
    "lots": ["lots"],
    "watchlist": ["watchlist"],
    "call_archive": ["calls", "archived_days"],
    "marks": ["long_term_marks"],
    "feedback": ["feedback"],
    "fund_calls": ["fund_calls"],
    "rsu_lots": ["fidelity_lots", "fidelity_events", "fidelity_holdings"],
}
FATHER = ("papa", "father")
WATCHLIST_REASON = ("On the watchlist", "নজরে রাখা তালিকায়")


class MigrationError(RuntimeError):
    pass


def table_checksum(db, sql: str, params=()) -> str:
    """sha256 over the rows of `sql` in a fixed order (every value as text), streamed so memory stays flat."""
    digest = hashlib.sha256()
    cur = db.execute(sql, list(params))
    while True:
        batch = cur.fetchmany(1000)
        if not batch:
            return digest.hexdigest()
        for row in batch:
            digest.update(json.dumps([None if v is None else str(v) for v in row]).encode() + b"\n")


def _v1(db, table):
    sql = f"select * from {table} order by all"
    return db.execute(f"select count(*) from {table}").fetchone()[0], table_checksum(db, sql)


def _v2(db, path: Path):
    sql = f"select * from read_parquet('{path}') order by all"
    return db.execute(f"select count(*) from read_parquet('{path}')").fetchone()[0], table_checksum(db, sql)


def _combine(parts: dict) -> str:
    return hashlib.sha256(json.dumps(parts, sort_keys=True).encode()).hexdigest()


def _ist(value) -> str:
    if value is None:
        return "1970-01-01T05:30:00+05:30"
    if not isinstance(value, datetime):
        value = datetime.fromisoformat(str(value))
    return value.replace(microsecond=0, tzinfo=None).isoformat() + "+05:30"


def _feedback_rows(db) -> list[dict]:
    rows = db.execute('select id, "at", author, text, status from feedback order by id').fetchall()
    return [{"id": f"v1_{i}", "person": "father" if (a or "").lower() in FATHER else "owner", "text": t or "",
             "status": "received" if s == "new" else "understood", "created_at": _ist(at)} for i, at, a, t, s in rows]


def _list_rows(db) -> list[dict]:
    rows = db.execute("select symbol, exchange, added_at from watchlist where removed_at is null "
                      "order by added_at, symbol").fetchall()
    return [{"list_name": "watchlist", "symbol": sym, "exchange": ex if ex in ("NSE", "BSE") else "NSE", "rank": n,
             "reason": WATCHLIST_REASON[0], "reason_bn": WATCHLIST_REASON[1], "since": _ist(at)}
            for n, (sym, ex, at) in enumerate(rows, start=1)]


def _sql_value(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def _seed_sql(tables: dict[str, list[dict]]) -> str:
    out = ["-- v1 -> v2 seed for D1 (idempotent). Generated by sp migrate-v2."]
    for table, rows in tables.items():
        cols = list(jobrun.CONTRACT["tables"][table]["columns"])
        for row in rows:
            out.append(f"insert or replace into {table} ({', '.join(cols)}) values "
                       f"({', '.join(_sql_value(row.get(c)) for c in cols)});")
    return "\n".join(out) + "\n"


def migrate(db, out_dir: Path | str) -> dict:
    """Copy every record type, then verify. Returns the report (also written to `manifest.json`)."""
    out = Path(out_dir)
    types = {}
    for rtype, tables in RECORD_TYPES.items():
        (out / rtype).mkdir(parents=True, exist_ok=True)
        parts = {}
        for table in tables:
            path = out / rtype / f"{table}.parquet"
            db.execute(f"copy (select * from {table} order by all) to '{path}' (format parquet, compression zstd)")
            parts[table] = path
        types[rtype] = parts
    d1 = {"feedback": _feedback_rows(db), "lists": _list_rows(db)}
    (out / "d1").mkdir(parents=True, exist_ok=True)
    for table, rows in d1.items():
        (out / "d1" / f"{table}.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False))
        shape = jobrun.CONTRACT["tables"][table]["columns"]
        bad = [p for r in rows for p in jobrun.check_shape(r, shape)]
        if bad:
            raise MigrationError(f"D1 {table} rows break the live contract: {bad[:3]}")
    (out / "d1" / "seed.sql").write_text(_seed_sql(d1))
    report = verify(db, out)
    report["d1"] = {t: len(r) for t, r in d1.items()}
    (out / "manifest.json").write_text(json.dumps(report, indent=1, sort_keys=True))
    return report


def verify(db, out_dir: Path | str) -> dict:
    """Read the copied files again and compare every record type to v1 (count and checksum). Raises on any difference."""
    out = Path(out_dir)
    types, wrong = {}, []
    for rtype, tables in RECORD_TYPES.items():
        t1, t2, c1, c2 = {}, {}, {}, {}
        try:
            for table in tables:
                c1[table], t1[table] = _v1(db, table)
                c2[table], t2[table] = _v2(db, out / rtype / f"{table}.parquet")
        except Exception as err:  # noqa: BLE001 - a missing or damaged file
            raise MigrationError(f"{rtype}: cannot read the copy ({type(err).__name__}); run the migration again.") from err
        n1, n2 = sum(c1.values()), sum(c2.values())
        types[rtype] = {"v1": n1, "v2": n2, "v1_sha": _combine(t1), "v2_sha": _combine(t2),
                        "tables": {t: {"v1": c1[t], "v2": c2[t]} for t in tables}}
        if (n1, types[rtype]["v1_sha"]) != (n2, types[rtype]["v2_sha"]):
            wrong.append(f"{rtype} (v1 {n1} rows, v2 {n2})")
    if wrong:
        raise MigrationError("Counts or contents differ for: " + ", ".join(wrong))
    return {"ok": True, "types": types}
