// Discovery by folder: every `api/src/<area>/` may hold `routes.ts`, `checks.ts` and
// `migrations/*.sql`. The Worker gets them as a generated static module (a bundle cannot scan
// folders); Node and the tests scan the same folders live.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import type { AreaModule, BuildInfo, Registry } from "../src/app";
import type { Migration } from "./run";

export const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const srcDir = (root: string) => join(root, "api/src");

export function areaNames(root = repoRoot): string[] {
  return (
    readdirSync(srcDir(root), { withFileTypes: true })
      .filter((d) => d.isDirectory() && d.name !== "generated")
      .map((d) => d.name)
      .filter((n) =>
        ["routes.ts", "checks.ts", "migrations"].some((f) => existsSync(join(srcDir(root), n, f))),
      )
      // `auth` first whatever its neighbours are called: its guard must be installed before any route reads it.
      .sort((a, b) => (a === "auth" ? -1 : b === "auth" ? 1 : a < b ? -1 : a > b ? 1 : 0))
  );
}

export function migrationFiles(root = repoRoot): Migration[] {
  return areaNames(root)
    .flatMap((a) => {
      const dir = join(srcDir(root), a, "migrations");
      return existsSync(dir)
        ? readdirSync(dir)
            .filter((f) => f.endsWith(".sql"))
            .map((f) => ({ name: f, sql: readFileSync(join(dir, f), "utf8") }))
        : [];
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

const tomlDb = (file: string) =>
  /database_id\s*=\s*"([^"]+)"/.exec(readFileSync(file, "utf8"))?.[1] ?? "";
export function buildInfo(root = repoRoot): BuildInfo {
  const pick = (f: string) => (existsSync(join(root, f)) ? tomlDb(join(root, f)) : "");
  return { productionDb: pick("wrangler.toml"), previewDb: pick("wrangler.preview.toml") };
}

/** The live registry for Node and tests. */
export async function loadRegistry(root = repoRoot): Promise<Registry> {
  const areas: AreaModule[] = [];
  for (const name of areaNames(root)) {
    const load = async (f: string) =>
      existsSync(join(srcDir(root), name, f))
        ? await import(pathToFileURL(join(srcDir(root), name, f)).href)
        : {};
    const r = await load("routes.ts");
    const c = await load("checks.ts");
    areas.push({ name, routes: r.default, checks: c.default });
  }
  return { areas, migrations: migrationFiles(root), buildInfo: buildInfo(root) };
}

/** Writes api/src/generated/registry.ts (for the Worker) and api/.generated/migrations/ (for wrangler). */
export function writeGenerated(root = repoRoot, version = "dev"): void {
  const names = areaNames(root);
  const imports: string[] = [];
  const entries = names.map((n, i) => {
    const has = (f: string) => existsSync(join(srcDir(root), n, f));
    if (has("routes.ts")) imports.push(`import r${i} from "../${n}/routes";`);
    if (has("checks.ts")) imports.push(`import c${i} from "../${n}/checks";`);
    return `  { name: ${JSON.stringify(n)}, routes: ${has("routes.ts") ? `r${i}` : "undefined"}, checks: ${has("checks.ts") ? `c${i}` : "undefined"} },`;
  });
  const out = join(srcDir(root), "generated");
  mkdirSync(out, { recursive: true });
  writeFileSync(
    join(out, "registry.ts"),
    `// Generated by api/migrate/build.ts. Do not edit; git-ignored.
import type { Registry } from "../app";
${imports.join("\n")}

export const registry: Registry = {
  areas: [
${entries.join("\n")}
  ],
  migrations: ${JSON.stringify(migrationFiles(root), null, 2)},
  buildInfo: ${JSON.stringify(buildInfo(root))},
};
export const version = ${JSON.stringify(version)};
`,
  );
  const flat = join(root, "api/.generated/migrations");
  rmSync(flat, { recursive: true, force: true });
  mkdirSync(flat, { recursive: true });
  for (const m of migrationFiles(root)) writeFileSync(join(flat, m.name), m.sql);
}
