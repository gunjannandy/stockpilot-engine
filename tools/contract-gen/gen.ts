// Generators: contract (Zod) -> index, JSON Schemas for Python, typed web client.
// Output is git-ignored and rebuilt by `pnpm gen` (CI runs it before anything reads it).

import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const src = join(root, "contract/src");
const outSchemas = join(root, "contract/generated/schemas");
const outClient = join(root, "web/src/generated/client.ts");

// `pnpm gen` is called by CI, by `pnpm test` and by Python tests that pytest-xdist runs side by side.
// Two runs must never corrupt each other: one run at a time (lock), every file replaced in one
// step (write then rename), and nothing deleted before the new output is in place.
const lockDir = join(
  tmpdir(),
  `stockpilot-gen-${createHash("sha1").update(root).digest("hex").slice(0, 12)}.lock`,
);
const sleep = (ms: number) => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
function acquireLock() {
  const deadline = Date.now() + 120_000;
  for (;;) {
    try {
      mkdirSync(lockDir);
      return;
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code !== "EEXIST") throw e;
      // A run that died holding the lock must not block everyone: a lock older than 60 s is stale.
      try {
        if (Date.now() - statSync(lockDir).mtimeMs > 60_000)
          rmSync(lockDir, { recursive: true, force: true });
      } catch {}
      if (Date.now() > deadline) throw new Error(`contract-gen: could not get ${lockDir} in 120 s`);
      sleep(100);
    }
  }
}
acquireLock();
process.on("exit", () => rmSync(lockDir, { recursive: true, force: true }));

const written = new Set<string>();
function writeAtomic(path: string, data: string) {
  mkdirSync(dirname(path), { recursive: true });
  const tmp = `${path}.${process.pid}.tmp`;
  writeFileSync(tmp, data);
  renameSync(tmp, path);
  written.add(path);
}

function areaFiles(dir: string, depth = 0): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) return depth < 1 ? areaFiles(p, depth + 1) : [];
      return name.endsWith(".ts") && name !== "index.ts" && !name.endsWith(".test.ts") ? [p] : [];
    });
}

// 1. The index: one export line per area file, so a new area never edits a shared file.
const files = areaFiles(src);
const indexLines = files.map((f) => `export * from "./${relative(src, f).replace(/\.ts$/, "")}";`);
writeAtomic(
  join(src, "index.ts"),
  `// Generated by tools/contract-gen. Do not edit; git-ignored.\n${indexLines.join("\n")}\n`,
);

// 2. JSON Schemas (Python validates every row against them). Import after the index exists.
const { datasets, routes } = await import(join(src, "index.ts"));
const emit = (name: string, schema: z.ZodType) =>
  writeAtomic(
    join(outSchemas, `${name}.schema.json`),
    `${JSON.stringify(z.toJSONSchema(schema), null, 2)}\n`,
  );
for (const [name, d] of Object.entries(datasets) as [string, { row: z.ZodType }][])
  emit(`dataset.${name}`, d.row);
for (const [id, r] of Object.entries(routes) as [
  string,
  { request: z.ZodType; response: z.ZodType },
][]) {
  emit(`route.${id}.request`, r.request);
  emit(`route.${id}.response`, r.response);
}
const manifest = {
  datasets: Object.fromEntries(
    (Object.entries(datasets) as [string, { job: string; writeBudget: number }][]).map(([n, d]) => [
      n,
      { job: d.job, write_budget: d.writeBudget },
    ]),
  ),
  routes: Object.fromEntries(
    (Object.entries(routes) as [string, { method: string; path: string; auth: string }][]).map(
      ([id, r]) => [id, { method: r.method, path: r.path, auth: r.auth }],
    ),
  ),
};
writeAtomic(
  join(root, "contract/generated/manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
);

// 3. The typed web client: one method per route, request and response checked by the contract.
const methods = Object.keys(routes).map((id) => {
  const camel = id.replace(/_(\w)/g, (_, c: string) => c.toUpperCase());
  return `  ${camel}: (input: z.input<typeof routes.${id}.request> = {} as never) =>\n    call(routes.${id}, input) as Promise<z.output<typeof routes.${id}.response>>,`;
});
writeAtomic(
  outClient,
  `// Generated by tools/contract-gen. Do not edit; git-ignored.
import { routes } from "@stockpilot/contract";
import type { z } from "zod";

export type Fetcher = (url: string, init?: RequestInit) => Promise<Response>;

export function createClient(fetcher: Fetcher = (u, i) => fetch(u, i), base = "") {
  async function call(r: { method: string; path: string; request: z.ZodType; response: z.ZodType }, input: unknown) {
    const body = r.method === "GET" ? undefined : JSON.stringify(r.request.parse(input));
    const res = await fetcher(base + r.path, {
      method: r.method,
      headers: body ? { "content-type": "application/json" } : undefined,
      body,
    });
    if (!res.ok) throw new Error(\`\${r.method} \${r.path} failed: \${res.status}\`);
    return r.response.parse(await res.json());
  }
  return {
${methods.join("\n")}
  };
}
export type Client = ReturnType<typeof createClient>;
`,
);
// Drop schemas of datasets and routes that no longer exist, only now that the new ones are in place.
for (const name of readdirSync(outSchemas)) {
  const p = join(outSchemas, name);
  if (!written.has(p)) rmSync(p, { force: true });
}
console.log(`contract-gen: ${files.length} area files, ${Object.keys(routes).length} routes`);
